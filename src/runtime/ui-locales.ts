const columns: Record<StoryLocale, number> = {
  ja: 1,
  ko: 2,
  "zh-Hant-TW": 3,
  "yue-Hant-HK-MO": 4,
};
export function uiText(source: string, locale: UiLocale): string {
  if (locale === "zh") return source;
  const exact = rows.find((r) => r.includes(source));
  if (exact) return exact[columns[locale]];
  let result = source;
  for (const row of [...rows].sort(
    (a, b) =>
      Math.max(...b.map((x) => x.length)) - Math.max(...a.map((x) => x.length)),
  ))
    for (const candidate of row)
      if (candidate.length > 1 && result.includes(candidate)) {
        result = result.split(candidate).join(row[columns[locale]]);
        break;
      }
  return result;
}
